"""Generates host/pemu_hop.h: the one place that says which number a HOP_<name> ("host operation") has.

The emulator proper (src/) never names a host syscall number.  It asks the host for an operation by name, hs(HOP_openat, ...), and the
host layer (host/) turns the name into whatever the host needs.  On a Linux host that is the host's own syscall number (HOP_x == SYS_x,
guarded by #ifdef SYS_x because the headers of x86_64 and aarch64 differ); another host backend supplies its own meaning for the same names.

PEMU_HOP_SCRAMBLE=1 ./build.sh builds a pemu whose HOP_ numbers are NOT Linux numbers (they are translated back only inside host_syscall()).
If that build passes the tests, nothing in src/ relies on HOP_x being equal to a Linux syscall number.

The list of names is every HOP_<name> used under src/.   usage: python3 tools/gen_hop.py [--check] [ROOT]"""
import os
import re
import sys

TOKEN = re.compile(r"\bHOP_([a-z0-9_]+)\b")

# Syscalls newer than an old libc's headers (glibc < 2.35 has no SYS_fchmodat2 ...).  Their numbers are the same on every architecture (the common
# table from 424 on), so the Linux backend can name them itself.  Without this entry the name exists only when the host's header has it.
# Keep this list short and only add a number that is the same on x86_64 and aarch64.
FALLBACK = {"fchmodat2": 452, "io_uring_enter": 426, "io_uring_register": 427, "io_uring_setup": 425}


def names(root):
    found = set()
    for dp, _, fs in os.walk(os.path.join(root, "src")):
        for f in fs:
            if f.endswith((".h", ".c")):
                with open(os.path.join(dp, f), encoding="utf-8", errors="replace") as fh:
                    found.update(TOKEN.findall(fh.read()))
    return sorted(found)


def render(ns):
    o = []
    w = o.append
    w("/* host/pemu_hop.h - GENERATED by tools/gen_hop.py, do not edit (build.sh checks that it is up to date).  SPDX-License-Identifier: Apache-2.0\n"
      " *\n"
      " * HOP_<name> is a host operation, named after the Linux syscall it is on a Linux host.  src/ uses only these names; this file is where they get\n"
      " * a value.  HOP_NR(op) gives the number the host kernel knows (Linux backend: the syscall number).  A name is defined only when the host's\n"
      " * headers have the syscall (#ifdef SYS_x), so '#ifdef HOP_x' in src/ asks \"does this host have it\".\n"
      " * PEMU_HOP_SCRAMBLE: HOP_ values are 0x5000 + index instead of the Linux number; HOP_NR() maps them back (anything else becomes -1, ENOSYS). */\n"
      "#ifndef PEMU_HOP_H\n#define PEMU_HOP_H\n")
    w("#ifdef PEMU_HOP_SCRAMBLE\n#define PEMU_HOP_BASE 0x5000\n#define PEMU_HOP_N %d\n#else\n#define HOP_NR(op) ((long) (op))\n#endif\n" % len(ns))
    for i, n in enumerate(ns):
        fb = FALLBACK.get(n)
        if fb is None:
            w("#ifdef SYS_%s\n#ifdef PEMU_HOP_SCRAMBLE\n#define HOP_%s (PEMU_HOP_BASE + %d)\n#else\n#define HOP_%s SYS_%s\n#endif\n#endif\n" % (n, n, i, n, n))
        else:
            w("#ifdef PEMU_HOP_SCRAMBLE\n#define HOP_%s (PEMU_HOP_BASE + %d)\n#elif defined(SYS_%s)\n#define HOP_%s SYS_%s\n#else\n#define HOP_%s %d      /* the host's headers predate it */\n#endif\n"
              % (n, i, n, n, n, n, fb))
    w("#ifdef PEMU_HOP_SCRAMBLE\nstatic const int pemu_hop_tab[PEMU_HOP_N] = {\n    [0 ... PEMU_HOP_N - 1] = -1,")
    for i, n in enumerate(ns):
        fb = FALLBACK.get(n)
        if fb is None:
            w("#ifdef SYS_%s\n    [%d] = SYS_%s,\n#endif" % (n, i, n))
        else:
            w("#ifdef SYS_%s\n    [%d] = SYS_%s,\n#else\n    [%d] = %d,\n#endif" % (n, i, n, i, fb))
    w("};\n"
      "static inline long HOP_NR(long op) { return (unsigned long) (op - PEMU_HOP_BASE) < (unsigned long) PEMU_HOP_N ? (long) pemu_hop_tab[op - PEMU_HOP_BASE] : -1L; }\n"
      "#endif\n#endif /* PEMU_HOP_H */\n")
    return "\n".join(o)


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    root = args[0] if args else os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
    out = os.path.join(root, "host", "pemu_hop.h")
    text = render(names(root))
    if "--check" in sys.argv:
        cur = open(out, encoding="utf-8").read() if os.path.exists(out) else ""
        if cur != text:
            print("host/pemu_hop.h is out of date: run python3 tools/gen_hop.py")
            return 1
        print("host hop table: up to date (%d operations)" % len(names(root)))
        return 0
    with open(out, "w", encoding="utf-8") as fh:
        fh.write(text)
    print("wrote host/pemu_hop.h (%d operations)" % len(names(root)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
