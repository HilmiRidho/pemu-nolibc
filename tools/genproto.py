import re,glob
skip={'__errno_location','__ctype_b_loc','__ctype_tolower_loc','__ctype_toupper_loc','main'}
noret={'exit','_exit','_Exit','abort','pthread_exit'}
defs={}
for f in sorted(glob.glob('host/rt/rt_*.h')):
    for l in open(f):
        m=re.match(r'^((?:RT_[A-Z_]+ )*)([A-Za-z_][A-Za-z_0-9 \*]*?[ \*])([A-Za-z_][A-Za-z_0-9]*)\(([^)]*)\)\s*\{',l)
        if not m: continue
        pre,ret,name,args=m.groups()
        if name in skip or ret.strip().startswith('static') or 'static' in ret.split() or name.startswith('rt_') or name in ('if','for','while','switch','return'): continue
        defs[name]=(ret.strip(),args)
out="/* generated by tools/genproto.py: the prototypes of every function host/rt/ defines (libc names).  SPDX-License-Identifier: Apache-2.0 */\n#ifndef PEMU_ABI_PROTO_H\n#define PEMU_ABI_PROTO_H\n"
for n,(r,a) in sorted(defs.items()):
    out+="%s %s(%s)%s;\n"%(r,n,a,' __attribute__((noreturn))' if n in noret else '')
out+="#endif\n"
open('host/abi/include/pemu_proto.h','w').write(out); print(len(defs),"prototypes")
