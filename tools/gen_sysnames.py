#!/usr/bin/env python3
"""Regenerate src/guest/x86_64/linux/sysnames.inc.h (x86_64 syscall number -> name, for the .pemu/pemu.log messages).
Needs the kernel UAPI headers of the build machine (linux-libc-dev); the generated file is checked in, so a normal build does not run this.
usage: python3 tools/gen_sysnames.py            (from anywhere)"""
import re, sys, os

def parse(path, rx):
    d = {}
    for line in open(path):
        m = re.match(rx, line)
        if m: d[int(m.group(2))] = m.group(1)
    return d

def emit(out, tab):
    top = max(tab) + 1
    with open(out, "w") as f:
        f.write("/* src/guest/x86_64/linux/sysnames.inc.h - generated by tools/gen_sysnames.py; do not edit. SPDX-License-Identifier: Apache-2.0 */\n")
        f.write("/* syscall number -> name of the x86_64 guest ABI, used only to make .pemu/pemu.log readable */\n")
        f.write("static const char *const pemu_sysnames[%d] = {\n" % top)
        for n in sorted(tab): f.write('    [%d] = "%s",\n' % (n, tab[n]))
        f.write("};\n#define PEMU_NSYSNAMES %d\n" % top)

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
x86 = None
for p in ("/usr/include/x86_64-linux-gnu/asm/unistd_64.h", "/usr/include/asm/unistd_64.h"):
    if os.path.exists(p): x86 = parse(p, r"#define __NR_(\w+)\s+(\d+)"); break
if not x86: sys.exit("kernel headers not found")
emit(sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, "src", "linux", "sysnames.inc.h"), x86)
